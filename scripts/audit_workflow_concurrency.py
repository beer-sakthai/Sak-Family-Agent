#!/usr/bin/env python3
"""Audit GitHub Actions concurrency groups and likely write races.

This intentionally uses only the Python standard library so it can run on a
fresh GitHub-hosted runner before project dependencies are installed.
"""
from __future__ import annotations

import argparse
import re
from dataclasses import dataclass
from pathlib import Path

WORKFLOW_SUFFIXES = {".yml", ".yaml", ".md"}
WRITE_MARKERS = re.compile(
    r"(?:issues|pull-requests|contents|actions|discussions):\s*write|"
    r"safe-outputs:|git\s+(?:push|commit)|gh\s+(?:pr|issue|api)|"
    r"create-pull-request|github-script",
    re.IGNORECASE,
)
GROUP_RE = re.compile(r"^\s*group:\s*(.+?)\s*$", re.MULTILINE)
CANCEL_RE = re.compile(r"^\s*cancel-in-progress:\s*(.+?)\s*$", re.MULTILINE)
NAME_RE = re.compile(r"^name:\s*[\"']?([^\"'\n]+)", re.MULTILINE)


@dataclass(frozen=True)
class Workflow:
    path: str
    name: str
    groups: tuple[str, ...]
    cancels: tuple[str, ...]
    write_markers: tuple[str, ...]
    generated: bool

    @property
    def has_concurrency(self) -> bool:
        return bool(self.groups)


def read_workflows(root: Path) -> list[Workflow]:
    result: list[Workflow] = []
    for path in sorted(root.iterdir()):
        if path.suffix not in WORKFLOW_SUFFIXES:
            continue
        text = path.read_text(encoding="utf-8", errors="replace")
        if path.suffix == ".md" and not text.startswith("---"):
            continue
        name_match = NAME_RE.search(text)
        name = name_match.group(1).strip() if name_match else path.stem
        groups = tuple(m.strip() for m in GROUP_RE.findall(text))
        cancels = tuple(m.strip() for m in CANCEL_RE.findall(text))
        markers = tuple(
            f"{line_no}:{line.strip()}"
            for line_no, line in enumerate(text.splitlines(), 1)
            if WRITE_MARKERS.search(line)
        )
        generated = path.name.endswith(".lock.yml") or path.name == "agentic_commands.yml"
        result.append(Workflow(path.name, name, groups, cancels, markers, generated))
    return result


def risk(wf: Workflow) -> str:
    if wf.path.endswith(".md") and Path(".github/workflows", wf.path[:-3] + ".lock.yml").exists():
        return "INFO: source template; generated lock file carries the runtime concurrency declaration"
    if not wf.has_concurrency and wf.write_markers:
        return "HIGH: write-capable workflow has no concurrency group"
    if not wf.has_concurrency:
        return "INFO: no concurrency declaration detected"
    if any("github.workflow }}-${{ github.ref }}" in group for group in wf.groups):
        if any("write" in marker.lower() or "safe-outputs" in marker.lower() for marker in wf.write_markers):
            return "MEDIUM: ref-scoped writer may race with other workflows touching the same resource"
    if any("github.workflow }}" in group and "github.ref" not in group and "run_id" not in group for group in wf.groups):
        return "MEDIUM: workflow-wide serialization may unnecessarily delay independent refs"
    if any(value.lower() in {"false", "${{ false }}"} for value in wf.cancels):
        return "LOW: queued writes are serialized rather than cancelled"
    return "LOW: explicit concurrency present"


def render(workflows: list[Workflow], repo: str) -> str:
    with_group = sum(w.has_concurrency for w in workflows)
    generated = sum(w.generated for w in workflows)
    high = sum(risk(w).startswith("HIGH") for w in workflows)
    medium = sum(risk(w).startswith("MEDIUM") for w in workflows)
    lines = [
        "# GitHub Actions Concurrency and Race-Condition Audit",
        "",
        f"Repository: `{repo}`  ",
        "Generated by `scripts/audit_workflow_concurrency.py`. This report is a static audit of committed workflow sources and generated Agentic Workflow files; it does not observe live run history.",
        "",
        "## Scope and totals",
        "",
        f"- Workflow sources inspected: **{len(workflows)}**",
        f"- Files with an explicit `concurrency` declaration: **{with_group}**",
        f"- Generated/locked workflow files: **{generated}**",
        f"- High-risk findings: **{high}**",
        f"- Medium-risk findings: **{medium}**",
        "",
        "## Race-condition model",
        "",
        "The audit treats a workflow as write-capable when it declares write permissions or contains common repository-write markers such as `safe-outputs`, `gh issue/pr/api`, `github-script`, or Git pushes. A concurrency group only serializes runs that evaluate to the same key; it does not coordinate different workflow names, different keys, or external repositories.",
        "",
        "The most important cross-workflow risks are therefore: two different workflows modifying the same issue or pull request without a shared key; branch/ref-scoped keys used for global resources such as labels, releases, or repository settings; and generated Agentic Workflow locks being edited instead of their source `.md` definitions.",
        "",
        "## Findings",
        "",
    ]
    for wf in workflows:
        groups = "; ".join(f"`{g}`" for g in wf.groups) if wf.groups else "—"
        cancels = "; ".join(f"`{c}`" for c in wf.cancels) if wf.cancels else "—"
        kind = "generated" if wf.generated else "source"
        lines.append(f"### `{wf.path}` ({kind})")
        lines.append("")
        lines.append(f"**Workflow:** {wf.name}  ")
        lines.append(f"**Concurrency group(s):** {groups}  ")
        lines.append(f"**Cancel-in-progress:** {cancels}  ")
        lines.append(f"**Risk:** {risk(wf)}  ")
        if wf.write_markers:
            lines.append("**Write-capability markers:** " + "; ".join(f"`{m}`" for m in wf.write_markers[:12]))
            if len(wf.write_markers) > 12:
                lines.append(f"  (plus {len(wf.write_markers) - 12} additional markers)")
        else:
            lines.append("**Write-capability markers:** none detected")
        lines.append("")
    lines.extend(
        [
            "## Recommended controls",
            "",
            "1. Keep one stable, resource-scoped key for each writer: pull-request number for PR comments/labels, issue number for issue mutations, environment for deployments, and a fixed repository key for global settings or releases.",
            "2. Do not use `cancel-in-progress: true` for workflows that publish releases, push commits, update branches, or perform non-idempotent external mutations unless the operation is demonstrably safe to interrupt.",
            "3. Keep generated `.lock.yml` files derived from their `.md` sources. The reconstruction workflow validates this boundary and reports generated files separately.",
            "4. Re-run this audit after adding or renaming a writer. A concurrency group is not a substitute for idempotency, API-level conditional updates, or a shared queue when two different workflows can target the same resource.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--workflow-dir", default=".github/workflows")
    parser.add_argument("--output", default="")
    parser.add_argument("--repo", default="local checkout")
    parser.add_argument("--fail-on-high", action="store_true")
    args = parser.parse_args()
    workflows = read_workflows(Path(args.workflow_dir))
    report = render(workflows, args.repo)
    if args.output:
        Path(args.output).parent.mkdir(parents=True, exist_ok=True)
        Path(args.output).write_text(report + "\n", encoding="utf-8")
    else:
        print(report)
    return 1 if args.fail_on_high and any(risk(w).startswith("HIGH") for w in workflows) else 0


if __name__ == "__main__":
    raise SystemExit(main())
