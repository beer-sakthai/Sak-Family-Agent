#!/usr/bin/env python3
"""Generate ``docs/mcp-deprecations.md`` from the MCP feature registry.

``personas/sakthai/mcp/lifecycle.py`` holds :data:`FEATURE_STATES`, the single
record of which parts of this package's MCP surface are Active, Deprecated or
Removed. The specification's own lifecycle policy (SEP-2596) asks for that set
to be *published* rather than left in release notes, so this renders it to a
document and ``tests/test_mcp_deprecations_doc.py`` fails when the two drift —
the same arrangement ``gen_dashboard_types.py`` has with the dashboard types.

Usage::

    python scripts/gen_mcp_deprecations.py           # write the file
    python scripts/gen_mcp_deprecations.py --check   # exit 1 if it would change

Output is deterministic: entries emit in registry order and the banner carries
no timestamp, so regenerating an unchanged registry is a no-op.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]

# There is no root-level `sakthai/` package; the installed one lives here.
sys.path.insert(0, str(REPO_ROOT / "personas"))
sys.path.insert(0, str(REPO_ROOT / "personas" / "sakthai"))

from sakthai.mcp.lifecycle import (  # noqa: E402
    FEATURE_STATES,
    MIN_DEPRECATION_DAYS,
    FeatureState,
)

OUTPUT_PATH = REPO_ROOT / "docs" / "mcp-deprecations.md"

BANNER = "<!-- Generated by scripts/gen_mcp_deprecations.py — do not edit by hand. -->"

PREAMBLE = f"""{BANNER}

# MCP feature lifecycle and deprecations

Every part of this package's MCP surface is in one of three states, following
the specification's own lifecycle policy (SEP-2596):

| State | Meaning |
|---|---|
| **Active** | Supported. Listed here only when its future is a question worth recording. |
| **Deprecated** | Still works, warns once per process, and will be removed no earlier than the date below. |
| **Removed** | Gone. Kept listed so an operator meeting an old config knows what happened. |

A deprecation runs for at least **{MIN_DEPRECATION_DAYS} days** between the day it
is announced and the earliest day it may be withdrawn. That window is enforced by
a test, not by good intentions.

The source of truth is `FEATURE_STATES` in
[`personas/sakthai/mcp/lifecycle.py`](../personas/sakthai/mcp/lifecycle.py).
This file is generated from it; edit the registry, then run
`python scripts/gen_mcp_deprecations.py`.
"""


def _section(title: str, features: list) -> list[str]:
    if not features:
        return []
    lines = [f"\n## {title}\n"]
    for feature in features:
        lines.append(f"### `{feature.id}`\n")
        lines.append(f"{feature.summary}\n")
        lines.append(f"{feature.rationale}\n")
        rows = []
        if feature.replacement:
            rows.append(f"| Use instead | `{feature.replacement}` |")
        if feature.deprecated_since:
            rows.append(f"| Deprecated since | {feature.deprecated_since} |")
        if feature.removal_not_before:
            rows.append(f"| Removal not before | {feature.removal_not_before} |")
        if feature.notice_days is not None:
            rows.append(f"| Notice given | {feature.notice_days} days |")
        if rows:
            lines.append("| | |")
            lines.append("|---|---|")
            lines.extend(rows)
            lines.append("")
    return lines


def render() -> str:
    lines = [PREAMBLE]
    for state, title in (
        (FeatureState.REMOVED, "Removed"),
        (FeatureState.DEPRECATED, "Deprecated"),
        (FeatureState.ACTIVE, "Active, with a note"),
    ):
        lines.extend(_section(title, [f for f in FEATURE_STATES if f.state is state]))
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="exit 1 if the file would change")
    args = parser.parse_args()

    rendered = render()
    if args.check:
        current = OUTPUT_PATH.read_text(encoding="utf-8") if OUTPUT_PATH.is_file() else ""
        if current != rendered:
            print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is stale.", file=sys.stderr)
            print("Run: python scripts/gen_mcp_deprecations.py", file=sys.stderr)
            return 1
        print(f"{OUTPUT_PATH.relative_to(REPO_ROOT)} is up to date.")
        return 0

    OUTPUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT_PATH.write_text(rendered, encoding="utf-8")
    print(f"Wrote {OUTPUT_PATH.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
