"""`docs/mcp-deprecations.md` must match the registry it is generated from.

The specification's lifecycle policy (SEP-2596) asks for the set of deprecated
features to be *published* rather than left in release notes. A published list
that silently falls behind the code is worse than none, so this fails CI the
moment the two disagree — the same arrangement `apps.yml` enforces between
`web/contracts.py` and the generated dashboard types.
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

from sakthai.mcp.lifecycle import FEATURE_STATES, FeatureState

REPO_ROOT = Path(__file__).resolve().parents[1]
GENERATOR = REPO_ROOT / "scripts" / "gen_mcp_deprecations.py"
DOC = REPO_ROOT / "docs" / "mcp-deprecations.md"


def test_the_generated_doc_is_current() -> None:
    result = subprocess.run(  # nosec B603 — fixed argv, no shell
        [sys.executable, str(GENERATOR), "--check"],
        capture_output=True,
        text=True,
        cwd=REPO_ROOT,
    )
    assert result.returncode == 0, (
        f"{DOC.relative_to(REPO_ROOT)} is stale.\n"
        f"{result.stdout}{result.stderr}\n"
        "Run: python scripts/gen_mcp_deprecations.py"
    )


def test_the_doc_exists_and_is_marked_generated() -> None:
    """So nobody edits it by hand and loses the change on the next run."""
    assert DOC.is_file()
    assert DOC.read_text(encoding="utf-8").startswith("<!-- Generated by")


def test_every_deprecated_feature_appears_in_the_doc() -> None:
    """The point of publishing is that a reader finds what they are looking for."""
    text = DOC.read_text(encoding="utf-8")
    for feature in FEATURE_STATES:
        if feature.state is not FeatureState.ACTIVE:
            assert feature.id in text, f"{feature.id} is missing from the published list"
            assert feature.removal_not_before in text, f"{feature.id} has no removal date"
