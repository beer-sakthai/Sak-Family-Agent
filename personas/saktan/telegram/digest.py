"""Hybrid Joy Stage Approval Digest formatter and Staged Markdown Report generator."""

from __future__ import annotations

import re
from dataclasses import dataclass
from datetime import UTC, datetime
from pathlib import Path

from ..config import REPO_ROOT


@dataclass
class ApprovalDigest:
    draft_id: str
    title: str
    summary: str
    channel: str
    inline_keyboard: list[list[dict[str, str]]]


def format_telegram_approval_digest(
    draft_id: str,
    title: str,
    summary: str,
    channel: str = "social",
) -> ApprovalDigest:
    """Format an interactive Telegram approval digest with callback buttons."""
    keyboard = [
        [
            {"text": "✅ Approve & Publish", "callback_data": f"approve:{draft_id}"},
            {"text": "✏️ Request Changes", "callback_data": f"revise:{draft_id}"},
        ]
    ]
    return ApprovalDigest(
        draft_id=draft_id,
        title=title,
        summary=summary,
        channel=channel,
        inline_keyboard=keyboard,
    )


def stage_markdown_report(
    title: str,
    content: str,
    persona: str = "saksit",
    output_dir: Path | None = None,
) -> Path:
    """Stage a long-form draft or model card into reports/staged for human review."""
    target_dir = output_dir or (REPO_ROOT / "personas" / persona / "reports" / "staged")
    target_dir.mkdir(parents=True, exist_ok=True)

    today = datetime.now(UTC).strftime("%Y-%m-%d")
    slug = re.sub(r"[^a-zA-Z0-9_\-]", "_", title.lower()).strip("_")
    filename = f"{today}_{slug}.md"
    file_path = target_dir / filename

    document = f"""---
title: {title}
persona: {persona}
date: {today}
status: staged
awaiting: Beer approval (hub-approved)
---

# {title}

> **Staged for Review**: This draft was generated by **{persona}**.
> Please review and approve with the Telegram 1-tap digest or by tagging `hub-approved`.

{content}
"""
    file_path.write_text(document, encoding="utf-8")
    return file_path
